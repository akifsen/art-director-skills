import assert from 'node:assert/strict';
import { initialState, reduce } from './state.js';
let s=reduce(initialState,{type:'open',id:'walk'});
s=reduce(s,{type:'toggle',item:'Keys'});
s=reduce(s,{type:'back'});
assert.deepEqual(s.checks.walk,['Keys']);
s=reduce(s,{type:'open',id:'studio'});
assert.equal(s.checks.studio,undefined);
s=reduce(s,{type:'open',id:'walk'});
assert.equal(reduce(s,{type:'finish',items:['Keys','Water bottle']}).screen,'pack');
s=reduce(s,{type:'toggle',item:'Water bottle'});
s=reduce(s,{type:'finish',items:['Keys','Water bottle']});
assert.equal(s.screen,'done');
s=reduce(s,{type:'back'});
s=reduce(s,{type:'toggle',item:'Keys'});
assert.equal(s.finished.walk,false);
assert.deepEqual(s.checks.walk,['Water bottle']);
s=reduce(s,{type:'restart'});
assert.deepEqual(s.checks.walk,[]);
assert.equal(s.screen,'pack');
